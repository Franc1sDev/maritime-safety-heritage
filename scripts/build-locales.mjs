// Builds the interface languages from the checked translation files in i18n/out (Section 3.1.6):
//   web/public/locales/<code>.json            the website loads the reader's language on demand
//   mobile-app/assets/i18n/<code>.json        bundled with the apps
//   backend/src/common/locales.ts             the server's own texts (rules, report reasons, error messages)
// A language is built only when every phrase is present and its placeholders match: node scripts/build-locales.mjs
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));
const web = read('i18n/source/web.json'), app = read('i18n/source/app.json'), server = read('i18n/source/server.json');
const late = existsSync(join(root, 'i18n/late.json')) ? read('i18n/late.json') : {};
mkdirSync(join(root, 'web/public/locales'), { recursive: true });
const serverLocales = {}, built = [];
for (const code of readdirSync(join(root, 'i18n/out')).sort()) {
  try { execFileSync(process.execPath, [join(root, 'i18n/validate.mjs'), code], { stdio: 'pipe' }); }
  catch (e) { console.log(`SKIPPED ${code}: ${String(e.stdout).trim().split('\n').pop()}`); continue; }
  const all = {};
  for (let i = 1; i <= 6; i++) Object.assign(all, read(`i18n/out/${code}/part${i}.json`));
  Object.assign(all, late[code] ?? {});
  const pick = (keys) => Object.fromEntries(keys.filter((k) => all[k] && all[k] !== k).map((k) => [k, all[k]]));
  const lateKeys = Object.keys(late[code] ?? {});
  writeFileSync(join(root, `web/public/locales/${code}.json`), JSON.stringify(pick([...web, ...lateKeys])));
  writeFileSync(join(root, `mobile-app/assets/i18n/${code}.json`), JSON.stringify(pick([...web, ...app, ...lateKeys])));
  serverLocales[code] = pick(server);
  built.push(code);
}
writeFileSync(join(root, 'backend/src/common/locales.ts'),
  `// Generated by scripts/build-locales.mjs from i18n/out. Do not edit by hand.\n/* eslint-disable */\nexport const SERVER_LOCALES: Record<string, Record<string, string>> = ${JSON.stringify(serverLocales, null, 1)};\n`);
console.log(`Built ${built.length} language(s): ${built.join(', ')}`);
